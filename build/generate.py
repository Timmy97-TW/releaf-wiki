#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
ReLeaf wiki: build the standard sub-pages.

    python3 build/generate.py            # write every page in pages.py
    python3 build/generate.py model       # write one
    python3 build/generate.py --list      # show what would be written

Each page in pages.py becomes <slug>/index.html at the wiki root, so the URL is
https://2026.igem.wiki/<team>/<slug> and nothing about the address depends on
which nav tab the page reads under.

SAFETY. This script refuses to overwrite a page a human has started. A page
counts as started once its "generated" marker comment has been removed, or once
the scaffold notes are gone. Pass --force to overwrite anyway, which you almost
never want: it throws away written prose.

The tab list, the order and the prev/next links all come from
assets/data/site-nav.js, which is the one place page addresses are declared.
"""

import html
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)

import pages as spec  # noqa: E402

MARKER = "<!-- generated by build/generate.py"

# The nav lives in JavaScript because the browser reads it. Rather than keep a
# second copy here, pull the fields we need straight out of that file.
NAV_JS = os.path.join(ROOT, "assets", "data", "site-nav.js")


def read_nav():
    src = open(NAV_JS, encoding="utf-8").read()
    tabs, order = [], []
    for block in re.finditer(
        r'\{\s*id:\s*"(?P<id>[\w-]+)",\s*name:\s*"(?P<name>[^"]+)"'
        r'.*?pages:\s*\[(?P<pages>.*?)\]\s*\}', src, re.S):
        tab = {"id": block.group("id"), "name": block.group("name"), "pages": []}
        for p in re.finditer(
            r'\{\s*title:\s*"(?P<title>[^"]+)",\s*slug:\s*"(?P<slug>[\w-]+)"',
            block.group("pages")):
            entry = {"title": p.group("title"), "slug": p.group("slug"),
                     "tab": tab["id"]}
            tab["pages"].append(entry)
            order.append(entry)
        tabs.append(tab)
    if not order:
        raise SystemExit("could not read any pages out of %s" % NAV_JS)
    return tabs, order


TABS, ORDER = read_nav()
TAB_NAME = {t["id"]: t["name"] for t in TABS}
BY_SLUG = {p["slug"]: p for p in ORDER}


def esc(t):
    return html.escape(t, quote=False)


# --------------------------------------------------------------- fragments --

def callout(kind, label, text):
    cls = {"medal": "callout--medal", "unproven": "callout--unproven",
           "borrowed": "callout--borrowed", "note": ""}[kind]
    return (
        '      <aside class="callout %s">\n'
        '        <b class="callout__label">%s</b>\n'
        '        <p>%s</p>\n'
        '      </aside>\n' % (cls, esc(label), esc(text)))


def award_block(award):
    kind, label, text, url = award
    cls = "callout--medal"
    return (
        '      <aside class="callout %s">\n'
        '        <b class="callout__label">%s</b>\n'
        '        <p>%s</p>\n'
        '        <p><a href="%s" target="_blank" rel="noopener">'
        'What iGEM asks for &rarr;</a></p>\n'
        '      </aside>\n' % (cls, esc(label), esc(text), url))


def figure(caption, n):
    return (
        '      <figure class="fig fig--pending">\n'
        '        <div class="fig__slot">Figure %d &middot; image not added yet'
        '<br />drop the file in <code>assets/img/</code> and replace this div '
        'with an &lt;img&gt;</div>\n'
        '        <figcaption><b>Figure %d.</b> %s</figcaption>\n'
        '      </figure>\n' % (n, n, esc(caption)))


def table(headers, rows):
    out = ['      <div class="tablewrap">\n        <table class="data">\n',
           '          <thead><tr>']
    out += ["<th>%s</th>" % esc(h) for h in headers]
    out.append("</tr></thead>\n          <tbody>\n")
    for r in rows:
        cells = "".join("<td>%s</td>" % (esc(c) if c else "&nbsp;") for c in r)
        out.append("            <tr>%s</tr>\n" % cells)
    out.append("          </tbody>\n        </table>\n      </div>\n")
    return "".join(out)


def tabgroup(items):
    strip = "".join(
        '            <button class="tabs__btn" role="tab" data-panel="%s" '
        'aria-controls="%s" id="tab-%s">%s</button>\n' % (tid, tid, tid, esc(name))
        for tid, name, _ in items)
    panels = "".join(
        '        <div class="tabs__panel" role="tabpanel" id="%s" '
        'aria-labelledby="tab-%s" hidden>\n'
        '          <h3>%s</h3>\n'
        '          <p class="scaffold">%s</p>\n'
        '        </div>\n' % (tid, tid, esc(name), esc(note))
        for tid, name, note in items)
    return ('      <div class="tabs">\n'
            '        <div class="tabs__strip" role="tablist">\n%s'
            '        </div>\n%s      </div>\n' % (strip, panels))


def section(sec, figno):
    out = ['      <section class="sec" id="%s">\n' %
           re.sub(r"[^\w-]+", "-", sec["h"].lower()).strip("-")]
    out.append("        <h2>%s</h2>\n" % esc(sec["h"]))
    if sec.get("note"):
        out.append('        <p class="scaffold">%s</p>\n' % esc(sec["note"]))
    if sec.get("callout"):
        out.append(callout(*sec["callout"]))
    for sub in sec.get("subs", []):
        out.append("        <h3>%s</h3>\n" % esc(sub["h"]))
        out.append('        <p class="scaffold">%s</p>\n' %
                   esc(sub["note"] or "Write this."))
    if sec.get("tabs"):
        out.append(tabgroup(sec["tabs"]))
    if sec.get("table"):
        out.append(table(*sec["table"]))
    for cap in sec.get("figs", []):
        figno += 1
        out.append(figure(cap, figno))
    out.append("      </section>\n\n")
    return "".join(out), figno


def footer(base):
    cols = []
    for tab in TABS:
        links = "".join(
            '          <li><a href="%s%s/">%s</a></li>\n' %
            (base, p["slug"], esc(p["title"])) for p in tab["pages"])
        cols.append('        <div>\n          <h3>%s</h3>\n          <ul>\n%s'
                    '          </ul>\n        </div>\n' % (esc(tab["name"]), links))
    return (
        '  <footer class="footer2">\n'
        '    <div class="footer2__inner">\n%s'
        '      <div class="footer2__legal">\n'
        '        <p><b>ReLeaf</b> &middot; GEMS Taiwan &middot; iGEM 2026 '
        '&middot; Biomanufacturing Village</p>\n'
        '        <p>&copy; 2026 &middot; Content on this wiki is licensed '
        'under a <a href="https://creativecommons.org/licenses/by/4.0/" '
        'rel="license">Creative Commons Attribution 4.0 International license</a>.</p>\n'
        '        <p>The repository used to create this website is available '
        'at <a href="https://gitlab.igem.org/2026/gems-taiwan">gitlab.igem.org/2026/gems-taiwan</a>.</p>\n'
        '        <p>Nothing on this wiki is fetched from a server outside iGEM. '
        'Before the wiki freeze, every image and font has to be re-hosted on '
        '<code>static.igem.wiki</code>.</p>\n'
        '      </div>\n'
        '    </div>\n'
        '  </footer>\n' % "".join(cols))


# ------------------------------------------------------------------- page ---

def build(page):
    slug = page["slug"]
    tab = page["tab"]
    base = "../"
    idx = next((i for i, p in enumerate(ORDER) if p["slug"] == slug), None)
    prev = ORDER[idx - 1] if idx not in (None, 0) else None
    nxt = ORDER[idx + 1] if idx is not None and idx + 1 < len(ORDER) else None

    body, figno = [], 0
    if page.get("award"):
        body.append(award_block(page["award"]))
    if page.get("intro"):
        body.append('      <p class="lede">%s</p>\n\n' % esc(page["intro"]))
    for sec in page["sections"]:
        chunk, figno = section(sec, figno)
        body.append(chunk)

    nav_links = []
    if prev:
        nav_links.append(
            '    <a class="is-prev" href="%s%s/"><b>Previous</b>'
            '<span>%s</span></a>\n' % (base, prev["slug"], esc(prev["title"])))
    if nxt:
        nav_links.append(
            '    <a class="is-next" href="%s%s/"><b>Next</b>'
            '<span>%s</span></a>\n' % (base, nxt["slug"], esc(nxt["title"])))

    return """<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="utf-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1" />
  <title>{title} | ReLeaf &middot; iGEM 2026</title>
  <meta name="description" content="{desc}" />
  <link rel="icon" href="{base}assets/img/logo.png" />
  <link rel="stylesheet" href="{base}assets/css/tokens.css" />
  <link rel="stylesheet" href="{base}assets/css/nav.css" />
  <link rel="stylesheet" href="{base}assets/css/page.css" />
</head>
<body>
{marker} do not hand-edit until you are ready to own this
     file. Once you start writing, delete this comment and the script will
     leave the page alone. -->

  <div id="site-nav" data-base="{base}" data-tab="{tab}" data-page="{slug}"></div>
  <div class="sitenav-spacer"></div>

  <header class="pagehead">
    <div class="pagehead__inner">
      <p class="pagehead__eyebrow">
        <a href="{base}">ReLeaf</a> <i>/</i> {tabname} <i>/</i> {title}
      </p>
      <h1 class="pagehead__title">{title}</h1>
      <p class="pagehead__lede">{lede}</p>
      <ul class="pagehead__meta">
        <li><b>Section</b><span>{tabname}</span></li>
        <li><b>Written by</b><span>{owner}</span></li>
        <li><b>Last updated</b><span>not yet</span></li>
        <li><b>Status</b><span>Scaffold</span></li>
      </ul>
    </div>
  </header>

  <div class="pagewrap">
    <details class="toc" open>
      <summary>Contents</summary>
      <div class="toc__inner"><p class="toc__title">On this page</p></div>
    </details>

    <main class="pagebody">
{body}
      <section class="refs" id="references">
        <h2 data-no-toc>References</h2>
        <ol>
          <li>Reference list not started. Write <code>[1]</code> anywhere in the
              prose above and it will link to the first item here.</li>
        </ol>
      </section>

      <div class="status">
        <b>This page is a scaffold.</b>
        Every italic note above is an instruction, not text to publish. Delete
        each one as you replace it, delete this box when the page is written,
        and set <span class="todo">Status</span> in the header to Draft and then
        to Final. Re-running <code>build/generate.py</code> will not touch this
        file once the generated marker at the top has been removed.
      </div>
    </main>
  </div>

  <nav class="pagenav" aria-label="Neighbouring pages">
{pagenav}  </nav>

{footer}
  <script src="{base}assets/data/site-nav.js"></script>
  <script src="{base}assets/js/nav.js"></script>
  <script src="{base}assets/js/page.js"></script>
</body>
</html>
""".format(
        title=esc(page["title"]),
        desc=esc(page["lede"]),
        lede=esc(page["lede"]),
        owner=esc(page.get("owner", "ReLeaf")),
        tab=tab,
        tabname=esc(TAB_NAME.get(tab, tab.title())),
        slug=slug,
        base=base,
        marker=MARKER,
        body="".join(body),
        pagenav="".join(nav_links),
        footer=footer(base),
    )


def main(argv):
    force = "--force" in argv
    listing = "--list" in argv
    wanted = [a for a in argv if not a.startswith("-")]

    todo = [p for p in spec.PAGES if not wanted or p["slug"] in wanted]
    if wanted and len(todo) != len(wanted):
        missing = set(wanted) - {p["slug"] for p in todo}
        raise SystemExit("no such page: %s" % ", ".join(sorted(missing)))

    written, skipped = [], []
    for page in todo:
        out = os.path.join(ROOT, page["slug"], "index.html")
        if listing:
            print(page["slug"])
            continue
        if os.path.exists(out) and not force:
            if MARKER not in open(out, encoding="utf-8").read():
                skipped.append(page["slug"])
                continue
        os.makedirs(os.path.dirname(out), exist_ok=True)
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(build(page))
        written.append(page["slug"])

    if listing:
        return
    print("wrote %d page(s)" % len(written))
    for s in written:
        print("  %s/" % s)
    if skipped:
        print("left alone, already being written by hand:")
        for s in skipped:
            print("  %s/" % s)


if __name__ == "__main__":
    main(sys.argv[1:])
